#!/usr/bin/env python3
"""Packs artwork/*.flp into Dart data used by the rider and bike figures.

Run from the project root:  python3 tool/pack_art.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from art_geometry import fmt  # noqa: E402
from pack_bike import build_bike  # noqa: E402
from pack_rider import SHEETS, build_sheet  # noqa: E402

OUT = 'lib/core/game/rider/art/sheet/data'
HEADER = '// GENERATED by tool/pack_art.py from artwork/*.flp. Do not edit.\n\n'


def camel(key):
    return key[0].upper() + key[1:]


def write(name, text):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), 'w') as handle:
        handle.write(HEADER + text)


def rider_file(key, parts, anchors):
    lines = ['const Map<String, List<String>> rider%sParts = {' % camel(key)]
    for pid, shapes in parts:
        lines.append("  '%s': [" % pid)
        for shape in shapes:
            lines.append("    '%s|%s'," % (shape['name'], fmt(shape['poly'])))
        lines.append('  ],')
    lines.append('};')
    lines.append('')
    lines.append('const Map<String, List<double>> rider%sAnchors = {' % camel(key))
    for name, (x, y) in sorted(anchors.items()):
        lines.append("  '%s': [%.2f, %.2f]," % (name, x, y))
    lines.append('};')
    return '\n'.join(lines) + '\n'


def bike_file(base, left, right):
    out = ['const List<String> bikeStraightRows = [']
    out += ["  '%s|%s|%s'," % row for row in base]
    out.append('];')
    for label, rows in (('Left', left), ('Right', right)):
        out.append('')
        out.append('const List<String> bike%sTurnRows = [' % label)
        out += ["  '%s|%s|%s|%s|%s'," % row for row in rows]
        out.append('];')
    return '\n'.join(out) + '\n'


def main():
    rider = json.load(open('artwork/rider/Rider.flp'))
    bike = json.load(open('artwork/bike/Bike.flp'))
    for key in SHEETS:
        parts, anchors = build_sheet(rider, key)
        write('rider_%s_data.dart' % key, rider_file(key, parts, anchors))
    write('bike_data.dart', bike_file(*build_bike(bike)))
    print('packed', len(SHEETS), 'rider sheets and the bike')


if __name__ == '__main__':
    main()
