#!/usr/bin/env python3
"""Packs artwork/*.flp into Dart data used by the rider and bike figures.

Run from the project root:  python3 tool/pack_art.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from art_geometry import fmt  # noqa: E402
from pack_bike import build_combi_bike  # noqa: E402
from pack_rider import SHEETS, build_sheet  # noqa: E402

OUT = 'lib/core/game/rider/art/sheet/data'
HEADER = '// GENERATED by tool/pack_art.py from artwork/*.flp. Do not edit.\n\n'


def camel(key):
    return key[0].upper() + key[1:]


def write(name, text):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), 'w') as handle:
        handle.write(HEADER + text)


def rider_file(key, parts, anchors):
    lines = ['const Map<String, List<String>> rider%sParts = {' % camel(key)]
    for pid, shapes in parts:
        lines.append("  '%s': [" % pid)
        for shape in shapes:
            lines.append("    '%s|%s'," % (shape['name'], fmt(shape['poly'])))
        lines.append('  ],')
    lines.append('};')
    lines.append('')
    lines.append('const Map<String, List<double>> rider%sAnchors = {' % camel(key))
    for name, (x, y) in sorted(anchors.items()):
        lines.append("  '%s': [%.2f, %.2f]," % (name, x, y))
    lines.append('};')
    return '\n'.join(lines) + '\n'


def bike_file(base, left, right):
    out = ['const List<String> bikeStraightRows = [']
    out += ["  '%s|%s|%s'," % row for row in base]
    out.append('];')
    for label, rows in (('Left', left), ('Right', right)):
        out.append('')
        out.append('const List<String> bike%sTurnRows = [' % label)
        out += ["  '%s|%s|%s|%s|%s'," % row for row in rows]
        out.append('];')
    return '\n'.join(out) + '\n'


RIDER_FLP = ['artwork/rider/Rider/Rider.flp', 'artwork/rider/Rider.flp']
BIKE_FLP = ['artwork/bike/Bike/Bike.flp', 'artwork/bike/Bike.flp']
COMBI_FLP = 'artwork/combi/combi.flp'
FROM_COMBI = {'seated', 'bike'}


def first_existing(paths):
    for path in paths:
        if os.path.exists(path):
            return json.load(open(path))
    return None


def main():
    only = set(sys.argv[1:])
    combi = json.load(open(COMBI_FLP))
    rider = None if only and only <= FROM_COMBI else first_existing(RIDER_FLP)
    packed = []
    for key in SHEETS:
        if only and key not in only:
            continue
        source = combi if key in FROM_COMBI else rider
        if source is None:
            print('skipped %s: its .flp file was not found' % key)
            continue
        parts, anchors = build_sheet(source, key)
        write('rider_%s_data.dart' % key, rider_file(key, parts, anchors))
        packed.append(key)
    if not only or 'bike' in only:
        write('bike_data.dart', bike_file(*build_combi_bike(combi, first_existing(BIKE_FLP))))
        packed.append('bike')
    print('packed', ', '.join(packed))


if __name__ == '__main__':
    main()
